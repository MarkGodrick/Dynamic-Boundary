"""Build unified harmful_refusal bare request pool with full provenance metadata.

Pillar-1 of the data sourcing pipeline (see docs/data_sourcing_principles.md §2.1).

Sources (all participate in one global embedding dedup pass):
  1. HarmBench/standard (200) — author hand-written direct prompts.
     We deliberately exclude HarmBench/contextual (multi-turn-context, off-scope)
     and HarmBench/copyright (different construct: copyright vs harm refusal).
  2. AdvBench (520)            — machine-generated by Wizard-Vicuna-30B-Uncensored.
  3. StrongREJECT (313)        — 70% author original + 30% from prior datasets
     (AdvBench/DAN/MaliciousInstruct/HarmfulQ/MasterKey/...). Inner overlap with
     AdvBench is handled by the global dedup pass.
  4. Author-handwritten gap-fill (optional, ~30) — covers AILuminate Privacy
     and Suicide & Self-Harm categories absent from the published benchmarks.
     Loaded from data/harmful_refusal/gap_fill_items.jsonl when the file
     exists; otherwise silently skipped. Any pre-assigned canonical_category /
     subcategory / classification_meta is preserved so the annotation script
     skips these items as already-labeled.

Note: JailbreakBench is intentionally NOT in the bare pool. It is reserved for
the Pillar-3 validation benchmark (easy tier), where we further filter to its 55
"Original" items to avoid item-level leakage with HarmBench/AdvBench.

Output schema (per line of bare_requests.jsonl):
    id              : int   global id after dedup
    prompt          : str
    source          : str   harmbench / advbench / strongreject / author_handwritten
    source_id       : int   index in the original dataset
    source_version  : str   HF dataset name + revision marker (or gap_fill version)
    download_date   : str   YYYY-MM-DD
    source_method   : str   human-written / machine-generated / mixed
    category        : str   may be empty (AdvBench has no native category)
    source_meta     : dict  any extra fields from the source
    # handwritten items additionally carry canonical_category / subcategory /
    # classification_meta when those were pre-assigned

Usage:
    conda run -n boundary python scripts/data_prep/build_bare_harmful_refusal.py
"""

import argparse
import json
from datetime import date
from pathlib import Path

import numpy as np
from datasets import load_dataset
from tqdm import tqdm


DOWNLOAD_DATE = date.today().isoformat()


def load_harmbench_standard() -> list[dict]:
    ds = load_dataset("walledai/HarmBench", "standard", split="train")
    return [
        {
            "prompt": row["prompt"],
            "source": "harmbench",
            "source_id": i,
            "source_version": "walledai/HarmBench@standard",
            "download_date": DOWNLOAD_DATE,
            "source_method": "human-written",
            "category": row["category"],
            "source_meta": {},
        }
        for i, row in enumerate(ds)
    ]


def load_advbench() -> list[dict]:
    ds = load_dataset("walledai/AdvBench", split="train")
    return [
        {
            "prompt": row["prompt"],
            "source": "advbench",
            "source_id": i,
            "source_version": "walledai/AdvBench",
            "download_date": DOWNLOAD_DATE,
            "source_method": "machine-generated",
            "category": "",
            "source_meta": {"target": row["target"]},
        }
        for i, row in enumerate(ds)
    ]


def load_strongreject() -> list[dict]:
    ds = load_dataset("walledai/StrongREJECT", split="train")
    out = []
    for i, row in enumerate(ds):
        inner = row["source"]
        method = "human-written" if inner == "custom" else "mixed"
        out.append({
            "prompt": row["prompt"],
            "source": "strongreject",
            "source_id": i,
            "source_version": "walledai/StrongREJECT",
            "download_date": DOWNLOAD_DATE,
            "source_method": method,
            "category": row["category"],
            "source_meta": {"inner_source": inner},
        })
    return out


def load_handwritten(path: Path) -> list[dict]:
    """Optional gap-fill items. File absence is not an error — returns [].

    Any pre-assigned canonical_category / subcategory / classification_meta is
    preserved so the annotation script skips these items as already labeled.
    """
    if not path.exists():
        return []
    out = []
    with open(path) as f:
        for i, line in enumerate(f):
            line = line.strip()
            if not line:
                continue
            raw = json.loads(line)
            item = {
                "prompt": raw["prompt"],
                "source": raw.get("source", "author_handwritten"),
                "source_id": raw.get("source_id", i),
                "source_version": raw.get("source_version", "gap_fill_v1"),
                "download_date": raw.get("download_date", DOWNLOAD_DATE),
                "source_method": raw.get("source_method", "human-written"),
                "category": raw.get("category", ""),
                "source_meta": raw.get("source_meta", {}),
            }
            for carry in ("canonical_category", "subcategory", "classification_meta"):
                if carry in raw:
                    item[carry] = raw[carry]
            out.append(item)
    return out


def compute_embeddings(texts: list[str], model_name: str, batch_size: int = 64) -> np.ndarray:
    from sentence_transformers import SentenceTransformer
    model = SentenceTransformer(model_name)
    return np.array(model.encode(
        texts, batch_size=batch_size, show_progress_bar=True, normalize_embeddings=True
    ))


def deduplicate(
    existing: list[dict],
    candidates: list[dict],
    threshold: float,
    model_name: str,
) -> tuple[list[dict], list[dict]]:
    """Return (kept, dropped). dropped items get a `_dedup_against` field for the report."""
    if not candidates:
        return [], []
    if not existing:
        return list(candidates), []

    existing_texts = [e["prompt"] for e in existing]
    candidate_texts = [c["prompt"] for c in candidates]
    all_embs = compute_embeddings(existing_texts + candidate_texts, model_name)
    existing_embs = all_embs[:len(existing_texts)]
    candidate_embs = all_embs[len(existing_texts):]
    sim_matrix = candidate_embs @ existing_embs.T

    kept, kept_embs, dropped = [], [], []
    for i, cand in enumerate(tqdm(candidates, desc="Dedup")):
        sims_existing = sim_matrix[i]
        max_idx = int(sims_existing.argmax())
        max_sim_existing = float(sims_existing[max_idx])
        if max_sim_existing >= threshold:
            cand = dict(cand)
            cand["_dedup_against"] = {
                "source": existing[max_idx]["source"],
                "source_id": existing[max_idx]["source_id"],
                "sim": round(max_sim_existing, 4),
            }
            dropped.append(cand)
            continue

        if kept_embs:
            kept_arr = np.stack(kept_embs)
            sims_kept = candidate_embs[i] @ kept_arr.T
            max_idx_k = int(sims_kept.argmax())
            max_sim_kept = float(sims_kept[max_idx_k])
            if max_sim_kept >= threshold:
                cand = dict(cand)
                cand["_dedup_against"] = {
                    "source": kept[max_idx_k]["source"],
                    "source_id": kept[max_idx_k]["source_id"],
                    "sim": round(max_sim_kept, 4),
                }
                dropped.append(cand)
                continue

        kept.append(cand)
        kept_embs.append(candidate_embs[i])

    return kept, dropped


def main():
    parser = argparse.ArgumentParser(description="Build unified harmful_refusal bare request pool")
    parser.add_argument("--sim-threshold", type=float, default=0.85)
    parser.add_argument("--output", type=str,
                        default="data/harmful_refusal/bare_requests.jsonl")
    parser.add_argument("--dedup-report", type=str,
                        default="results/data_prep/harmful_refusal/bare_dedup_report.json")
    parser.add_argument("--model", type=str, default="all-MiniLM-L6-v2")
    parser.add_argument("--handwritten", type=str,
                        default="data/harmful_refusal/gap_fill_items.jsonl",
                        help="Optional hand-written gap-fill items; silently skipped if absent")
    args = parser.parse_args()

    print("Loading sources...")
    harmbench = load_harmbench_standard()
    advbench = load_advbench()
    strongreject = load_strongreject()
    handwritten = load_handwritten(Path(args.handwritten))
    print(f"  HarmBench/standard: {len(harmbench)}")
    print(f"  AdvBench:           {len(advbench)}")
    print(f"  StrongREJECT:       {len(strongreject)}")
    print(f"  Handwritten:        {len(handwritten)}" + (
        f" (from {args.handwritten})" if handwritten else " (file absent — skipped)"))
    raw_total = len(harmbench) + len(advbench) + len(strongreject) + len(handwritten)
    print(f"  Raw total:          {raw_total}")

    pool = list(harmbench)
    all_dropped = []

    print(f"\nDedup AdvBench against HarmBench...")
    kept, dropped = deduplicate(pool, advbench, args.sim_threshold, args.model)
    print(f"  Kept {len(kept)} / {len(advbench)} from AdvBench (dropped {len(dropped)})")
    pool.extend(kept)
    all_dropped.extend(dropped)

    print(f"\nDedup StrongREJECT against HarmBench+AdvBench...")
    kept, dropped = deduplicate(pool, strongreject, args.sim_threshold, args.model)
    print(f"  Kept {len(kept)} / {len(strongreject)} from StrongREJECT (dropped {len(dropped)})")
    pool.extend(kept)
    all_dropped.extend(dropped)

    if handwritten:
        print(f"\nDedup handwritten against pool...")
        kept, dropped = deduplicate(pool, handwritten, args.sim_threshold, args.model)
        print(f"  Kept {len(kept)} / {len(handwritten)} from handwritten (dropped {len(dropped)})")
        pool.extend(kept)
        all_dropped.extend(dropped)

    from collections import Counter
    source_counts = Counter(item["source"] for item in pool)
    print(f"\n=== Final pool: {len(pool)} ({raw_total - len(pool)} removed by dedup) ===")
    for src, cnt in source_counts.most_common():
        print(f"  {src}: {cnt}")

    method_counts = Counter(item["source_method"] for item in pool)
    print(f"\nGeneration method distribution:")
    for m, cnt in method_counts.most_common():
        print(f"  {m}: {cnt}")

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        for i, item in enumerate(pool):
            item["id"] = i
            f.write(json.dumps(item, ensure_ascii=False) + "\n")
    print(f"\nSaved bare pool to {out_path}")

    report_path = Path(args.dedup_report)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    with open(report_path, "w") as f:
        json.dump({
            "sim_threshold": args.sim_threshold,
            "embedding_model": args.model,
            "raw_total": raw_total,
            "final_total": len(pool),
            "removed": raw_total - len(pool),
            "by_source": dict(source_counts),
            "by_method": dict(method_counts),
            "dropped_items": all_dropped,
        }, f, indent=2, ensure_ascii=False)
    print(f"Saved dedup report to {report_path}")


if __name__ == "__main__":
    main()
